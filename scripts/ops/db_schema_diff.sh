#!/usr/bin/env bash
# Compare the schema of a v1-restored database against a fresh v2 migration.
#
# Usage: scripts/ops/db_schema_diff.sh <v1_db> <v2_db> [psql-connection-args...]
#
# Dumps both schemas (no owners, no privileges, no comments), normalises
# incidental noise, and diffs. Differences listed in the schema-known-deltas.txt
# beside this script (grep -f patterns, one per line, '#' comments allowed) are
# filtered out. Keep the file next to this script: the path below is relative to
# the script, and a scripts/ reorg once left it pointing at nothing.
# Exit 0 = schemas match modulo known deltas; exit 1 = unexplained drift.
set -euo pipefail

if [[ $# -lt 2 ]]; then
  echo "usage: $0 <v1_db> <v2_db> [connection args]" >&2
  exit 2
fi

V1_DB="$1"
V2_DB="$2"
shift 2

KNOWN_DELTAS="$(dirname "$0")/schema-known-deltas.txt"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

normalise() {
  # Drop psql housekeeping, comments, \restrict tokens, and blank lines;
  # collapse whitespace; canonicalise auto-generated identifier hashes
  # (Django appends an 8-hex hash to FK/index names — v1's still carry
  # pre-rename "workflow_" prefixes, pure noise); equate the two textual
  # forms of not-blank checks (v1 raw SQL `col <> ''` vs Django
  # CheckConstraint `NOT (col = '')`); then sort column/constraint lines
  # within each CREATE TABLE block (column order differs between v1's
  # migration history and v2's fresh initials; data restores by name).
  grep -vE '^(--|SET |SELECT pg_catalog|\\connect|\\restrict|\\unrestrict|$)' |
    sed -E '
      s/[[:space:]]+/ /g; s/ $//;
      s/ADD CONSTRAINT [a-zA-Z0-9_]+ (PRIMARY KEY|UNIQUE|FOREIGN KEY)/ADD CONSTRAINT * \1/;
      s/(CONSTRAINT|INDEX) ([a-zA-Z0-9_]+_)[0-9a-f]{6,12}(_[a-zA-Z0-9_]*)? /\1 HASHNAME /g;
      # Not-blank checks appear three ways with identical semantics (NULL passes,
      # blank fails): v1 raw not-equals-empty-string, plain negated equals-empty-string,
      # and Django 6 null-safe negated equals-empty-string-and-not-null. One token for all.
      s/CHECK \(+NOT \(+\(?("?[a-zA-Z0-9_]+"?)\)?(::text)? = '\'''\''::text\) AND \("?[a-zA-Z0-9_]+"? IS NOT NULL\)\)+/CHECK NOTBLANK(\1)/g;
      s/CHECK \(+NOT \(\(?("?[a-zA-Z0-9_]+"?)\)?(::text)? = '\'''\''::text\)\)+/CHECK NOTBLANK(\1)/g;
      s/CHECK \(+\(?("?[a-zA-Z0-9_]+"?)\)?(::text)? <> '\'''\''::text\)+,?/CHECK NOTBLANK(\1)/g;
      # v1 tables predate identity columns (serial + sequence); fresh Django 6
      # emits GENERATED ... AS IDENTITY, and AutoField became BigAutoField.
      # Same data contract (int widens into bigint; COPY works with both), so
      # canonicalise ONLY the auto-pk columns (id / history_id) to one token.
      s/^ ?(id|history_id) (integer|bigint) NOT NULL( GENERATED BY DEFAULT AS IDENTITY.*)?$/\1 AUTOPK/;
      # Constraint-name fossils: v1 sequences and inline CHECK names kept
      # pre-rename "workflow_" prefixes. Structure is guarded; names are not.
      s/SEQUENCE NAME [a-zA-Z0-9_.]+//;
      s/CONSTRAINT [a-zA-Z0-9_]+ CHECK/CONSTRAINT * CHECK/;
    ' |
    awk '
      # Canonical, order-insensitive form: tag column lines with their table,
      # join two-line ALTER TABLE statements, drop serial/identity sequence
      # machinery (canonicalised by the AUTOPK rule above), sort globally.
      /^ ?(SEQUENCE NAME|START WITH|INCREMENT BY|NO MINVALUE|NO MAXVALUE|CACHE|AS (integer|bigint);|\),?$)/ { next }
      /^ ?(CREATE SEQUENCE|ALTER SEQUENCE|COMMENT ON)|SET DEFAULT nextval/ { next }
      /ALTER COLUMN (id|history_id) ADD GENERATED BY DEFAULT AS IDENTITY/ { next }
      /^CREATE TABLE/ { table=$3; print "TABLE " table; next }
      table != "" && /^\);/ { table=""; next }
      table != "" { sub(/,$/, ""); print "COLUMN " table " | " $0; next }
      /^ALTER TABLE/ { pending=$0; next }
      pending != "" { print pending " " $0; pending=""; next }
      { print }
    ' | sort -u
}

pg_dump --schema-only --no-owner --no-privileges "$@" "$V1_DB" | normalise > "$WORK/v1.sql"
pg_dump --schema-only --no-owner --no-privileges "$@" "$V2_DB" | normalise > "$WORK/v2.sql"

DIFF_OUT="$WORK/diff.txt"
diff -u "$WORK/v1.sql" "$WORK/v2.sql" > "$DIFF_OUT" || true

# Keep only real +/- lines, then strip known deltas.
grep -E '^[+-]' "$DIFF_OUT" | grep -vE '^(\+\+\+|---)' > "$WORK/changes.txt" || true
if [[ -f "$KNOWN_DELTAS" ]]; then
  grep -vE '^\s*(#|$)' "$KNOWN_DELTAS" > "$WORK/known.txt" || true
  if [[ -s "$WORK/known.txt" ]]; then
    grep -v -f "$WORK/known.txt" "$WORK/changes.txt" > "$WORK/unexplained.txt" || true
  else
    cp "$WORK/changes.txt" "$WORK/unexplained.txt"
  fi
else
  cp "$WORK/changes.txt" "$WORK/unexplained.txt"
fi

if [[ -s "$WORK/unexplained.txt" ]]; then
  echo "SCHEMA DRIFT (not covered by schema-known-deltas.txt):" >&2
  cat "$WORK/unexplained.txt" >&2
  echo >&2
  echo "Full diff kept at: $DIFF_OUT (copy it before the shell exits)" >&2
  cp "$DIFF_OUT" /tmp/db_schema_diff_last.txt
  echo "Copied full diff to /tmp/db_schema_diff_last.txt" >&2
  exit 1
fi

echo "Schemas match (modulo known deltas)."
